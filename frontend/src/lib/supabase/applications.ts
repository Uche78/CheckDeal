import { supabase } from './client';
import { getCurrentBroker } from './brokers';
import type { Application, ApplicationInsert, ApplicationUpdate, ApplicationWithBorrowers, ApplicationStats } from '../types/database';
import { logActivity } from './activity-logs';

/**
 * Generate a unique upload token for borrower portal
 */
function generateUploadToken(): string {
  return Math.random().toString(36).substring(2, 15) + Math.random().toString(36).substring(2, 15);
}

/**
 * Get all applications for the current broker
 */
export async function getApplications(): Promise<Application[]> {
  const broker = await getCurrentBroker();
  
  if (!broker) {
    throw new Error('Not authenticated');
  }
  
  const { data, error } = await supabase
    .from('applications')
    .select('*')
    .eq('broker_id', broker.id)
    .is('deleted_at', null)
    .order('created_at', { ascending: false });
  
  if (error) {
    console.error('Error fetching applications:', error);
    throw error;
  }
  
  return data || [];
}

/**
 * Get all applications with borrower information
 */
export async function getApplicationsWithBorrowers(): Promise<ApplicationWithBorrowers[]> {
  const broker = await getCurrentBroker();
  
  if (!broker) {
    throw new Error('Not authenticated');
  }

  const { data, error } = await supabase
    .from('applications')
    .select(`
      *,
      borrowers (*)
    `)
    .eq('broker_id', broker.id)
    .is('deleted_at', null)
    .order('created_at', { ascending: false });

  if (error) {
    console.error('Error fetching applications:', error);
    throw error;
  }

  // Filter out soft-deleted borrowers from each application
  const filteredData = (data || []).map(app => ({
    ...app,
    borrowers: app.borrowers?.filter(b => !b.deleted_at) || []
  }));

  return filteredData;
}

/**
 * Get a single application by ID
 */
export async function getApplicationById(id: string): Promise<Application | null> {
  const broker = await getCurrentBroker();
  
  if (!broker) {
    throw new Error('Not authenticated');
  }
  
  const { data, error } = await supabase
    .from('applications')
    .select('*')
    .eq('id', id)
    .eq('broker_id', broker.id)
    .is('deleted_at', null)
    .single();
  
  if (error) {
    if (error.code === 'PGRST116') {
      // No rows returned
      return null;
    }
    console.error('Error fetching application:', error);
    throw error;
  }
  
  return data;
}

/**
 * Get a single application with borrowers by ID
 */
export async function getApplicationWithBorrowersById(id: string): Promise<ApplicationWithBorrowers | null> {
  const { data, error } = await supabase
    .from('applications')
    .select(`
      *,
      borrowers!inner(*)
    `)
    .eq('id', id)
    .is('deleted_at', null)
    .single();

  if (error) {
    console.error('Error fetching application:', error);
    return null;
  }

  // Filter out soft-deleted borrowers
  if (data && data.borrowers) {
    data.borrowers = data.borrowers.filter(b => !b.deleted_at);
  }

  return data;
}

/**
 * Create a new application
 */
export async function createApplication(application: Omit<ApplicationInsert, 'broker_id' | 'upload_token'>): Promise<Application> {
  const broker = await getCurrentBroker();
  
  if (!broker) {
    throw new Error('Not authenticated');
  }

// Don't send upload_token - let Supabase generate it with uuid_generate_v4()
  const { data, error } = await supabase
    .from('applications')
    .insert({
      ...application,
      broker_id: broker.id,
      // upload_token will be auto-generated by database
    })  
    .select()
    .single();
  
if (error) {
  console.error('Supabase error creating application:', {
    message: error.message,
    details: error.details,
    hint: error.hint,
    code: error.code,
  });
  throw error;
}

// Log activity
  await logActivity(
    data.id,
    'application_created',
    'Application created',
    { property_address: application.property_address }
  );
  
  return data;
}

