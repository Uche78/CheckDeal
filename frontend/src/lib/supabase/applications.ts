/**
 * Search and filter applications
 */
export async function searchApplications(
  searchTerm?: string,
  status?: Application['status'],
  dateFrom?: Date,
  dateTo?: Date
): Promise<Application[]> {
  const broker = await getCurrentBroker();
  
  if (!broker) {
    throw new Error('Not authenticated');
  }
  
  let query = supabase
    .from('applications')
    .select('*')
    .eq('broker_id', broker.id)
    .is('deleted_at', null);
  
  // Apply filters
  if (status) {
    query = query.eq('status', status);
  }
  
  if (dateFrom) {
    query = query.gte('created_at', dateFrom.toISOString());
  }
  
  if (dateTo) {
    query = query.lte('created_at', dateTo.toISOString());
  }
  
  // Apply search term (searches in property_address and city)
  if (searchTerm && searchTerm.trim()) {
    query = query.or(`property_address.ilike.%${searchTerm}%,city.ilike.%${searchTerm}%`);
  }
  
  query = query.order('created_at', { ascending: false });
  
  const { data, error } = await query;
  
  if (error) {
    console.error('Error searching applications:', error);
    throw error;
  }
  
  return data || [];
}

/**
 * Subscribe to real-time changes for applications
 */
export function subscribeToApplications(
  callback: (payload: any) => void
) {
  return supabase
    .channel('applications-changes')
    .on(
      'postgres_changes',
      {
        event: '*',
        schema: 'public',
        table: 'applications',
      },
      callback
    )
    .subscribe();
}

/**
 * Get application statistics for the current broker
 */
export async function getApplicationStats() {
  const broker = await getCurrentBroker();
  
  if (!broker) {
    throw new Error('Not authenticated');
  }

  // Get all applications for this broker
  const { data: applications, error } = await supabase
    .from('applications')
    .select('status')
    .eq('broker_id', broker.id)
    .is('deleted_at', null);

  if (error) {
    console.error('Error fetching application stats:', error);
    throw error;
  }

  // Calculate stats
  const total = applications?.length || 0;
  const pending = applications?.filter(app => app.status === 'pending').length || 0;
  const in_progress = applications?.filter(app => app.status === 'in_progress').length || 0;
  const approved = applications?.filter(app => app.status === 'approved').length || 0;
  const denied = applications?.filter(app => app.status === 'denied').length || 0;
  const flagged = applications?.filter(app => app.status === 'flagged').length || 0;

  return {
    total,
    pending,
    in_progress,
    approved,
    denied,
    flagged,
  };
}

